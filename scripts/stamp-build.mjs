import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const now = new Date();
const stamp = now.toISOString().replace("T", " ").substring(0, 19) + " UTC";

const envPath = path.join(ROOT, "src", "lib", "build-stamp.ts");
fs.writeFileSync(
  envPath,
  `// Auto-generated by scripts/stamp-build.mjs — do not edit by hand.\n` +
    `export const BUILD_TIME = "${stamp}";\n`
);

console.log(`Build time stamped: ${stamp}`);
